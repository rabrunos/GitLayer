import test from 'node:test';
import assert from 'node:assert/strict';
import { _electron as electron } from 'playwright';
import { mkdtemp, mkdir, readFile, writeFile, rm, access } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import os from 'node:os';
import { pathToFileURL } from 'node:url';
import { waitUntil } from './wait.mjs';

test('explorador e abas: árvore, teclado, criação, contexto e fechamento sem fantasmas', { timeout: 180_000 }, async () => {
  const temp = await mkdtemp(path.join(os.tmpdir(), 'gitlayers-explorer-'));
  const repo = path.join(temp, 'explorer-fixture');
  const profile = path.join(temp, 'profile');
  const reports = path.resolve('.workshop/reports/explorer');
  const baseline = process.env.LAB_EXPLORER_BASELINE === '1';
  const evidence = { platform: process.platform, arch: process.arch, baseline, checks: [], errors: [] };
  let app;
  let page;
  try {
    await mkdir(reports, { recursive: true });
    await mkdir(repo); await mkdir(profile);
    const localApp = process.env.LAB_E2E_APP || (baseline ? 'dist-debug' : undefined);
    const dist = path.resolve(process.env.LAB_E2E_DIST || (baseline ? 'dist-debug' : 'dist'));
    const { GitLayers } = await import(pathToFileURL(path.join(dist, 'core/index.js')).href);
    const { resolveGitExecutable, normalizeProcessEnvironment, DISABLED_GIT_HOOKS } = await import(pathToFileURL(path.join(dist, 'core/platform.js')).href);
    const env = normalizeProcessEnvironment(process.env);
    for (const key of Object.keys(env)) if (/^GIT_/i.test(key) || key === 'ELECTRON_RUN_AS_NODE') delete env[key];
    Object.assign(env, { GIT_CONFIG_GLOBAL: '/dev/null', GIT_CONFIG_SYSTEM: '/dev/null', GIT_CONFIG_NOSYSTEM: '1', GIT_TERMINAL_PROMPT: '0', XDG_CONFIG_HOME: profile });
    const executable = await resolveGitExecutable(env);
    const git = args => execFileSync(executable, ['-c', `core.hooksPath=${DISABLED_GIT_HOOKS}`, ...args], { cwd: repo, env, encoding: 'utf8', windowsHide: true });
    git(['init', '-b', 'main']); git(['config', '--local', 'user.name', 'Explorer Test']); git(['config', '--local', 'user.email', 'test@example.invalid']); git(['config', '--local', 'core.autocrlf', 'false']);
    for (const folder of ['src/components', 'src/utils', 'docs/guides', 'empty']) await mkdir(path.join(repo, folder), { recursive: true });
    for (const [name, text] of Object.entries({ 'README.md': '# Explorer\n', 'package.json': '{"private":true}\n', 'src/components/Button.tsx': 'export const Button = () => null;\n', 'src/utils/file10.ts': 'export const ten = 10;\n', 'src/utils/file2.ts': 'export const two = 2;\n', 'docs/guides/start.md': '# Getting started\n' })) await writeFile(path.join(repo, name), text);
    git(['add', '.']); git(['commit', '-m', 'Explorer fixture']);
    const core = await GitLayers.open(repo); await core.init(); await core.create('ai'); await core.on('ai');
    await writeFile(path.join(repo, 'AGENTS.md'), 'Layer ai\n'); await core.add('ai', ['AGENTS.md']); await core.commit('ai', 'Layer fixture');
    await core.create('scripts'); await core.on('scripts');
    await mkdir(path.join(repo, 'scripts/nested'), { recursive: true });
    await writeFile(path.join(repo, 'scripts/nested/tool.ps1'), 'Write-Output "Layer scripts"\n');
    await core.add('scripts', ['scripts/nested/tool.ps1']); await core.commit('scripts', 'Scripts fixture');
    const electronExecutable = process.env.LAB_E2E_EXECUTABLE || (baseline ? (await import('electron')).default : path.resolve(`artifacts/Git Layers Lab-${process.platform}-${process.arch}/git-layers-lab${process.platform === 'win32' ? '.exe' : ''}`));
    app = await electron.launch({ executablePath: electronExecutable, args: [...(localApp ? [path.resolve(localApp)] : []), `--lab-profile=${profile}`, `--repo=${repo}`], env, chromiumSandbox: true });
    page = await app.firstWindow();
    page.on('pageerror', error => evidence.errors.push(error.message));
    await page.getByTestId('workspace').waitFor();
    evidence.visible = await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isVisible());
    assert.equal(evidence.visible, true);
    const readme = page.locator('.file-row').filter({ hasText: 'README.md' });
    // All clicks arrive before the first asynchronous disk read resolves.
    await readme.evaluate(row => { for (let i = 0; i < 6; i++) row.click(); });
    await page.getByRole('tab', { name: /README\.md/ }).first().waitFor();
    await waitUntil(async () => (await page.evaluate(() => window.lab.call('snapshot'))).ok);
    evidence.repeatedOpenTabs = await page.getByRole('tab', { name: /README\.md/ }).count();
    evidence.treeItems = await page.getByRole('treeitem').count();
    await page.screenshot({ path: path.join(reports, baseline ? 'before.png' : 'after-open.png') });
    if (baseline) { evidence.status = 'observed'; return; }
    assert.equal(evidence.repeatedOpenTabs, 1, 'Repeated clicks must not append duplicate React keys/tabs');
    evidence.checks.push('rapid-open-deduplicates-tabs');
    assert.ok(evidence.treeItems > 0, 'Explorer exposes a real accessible tree');
    const tree = page.getByRole('tree', { name: 'Arquivos do workspace' });
    const item = name => tree.locator(`[data-path="${name}"]`);
    const scriptsBadge = item('scripts/nested').getByRole('img', { name: 'layer/scripts', exact: true });
    assert.equal(await scriptsBadge.getAttribute('title'), 'layer/scripts');
    await page.getByRole('button', { name: 'Desativar Layer scripts', exact: true }).click();
    await page.getByRole('button', { name: 'Guardar e desativar', exact: true }).click();
    await page.getByRole('button', { name: 'Ativar Layer scripts', exact: true }).waitFor();
    await assert.rejects(access(path.join(repo, 'scripts')), { code: 'ENOENT' });
    await item('scripts/nested').waitFor({ state: 'detached' });
    await page.getByRole('button', { name: 'Ativar Layer scripts', exact: true }).click();
    await item('scripts/nested').waitFor();
    assert.equal(await readFile(path.join(repo, 'scripts/nested/tool.ps1'), 'utf8'), 'Write-Output "Layer scripts"\n');
    evidence.checks.push('layer-toggle-removes-empty-folders-restores-files-and-ref-tooltip');
    assert.equal(await item('docs/guides').count(), 1);
    await page.getByRole('button', { name: 'Opções do explorador' }).click();
    await page.getByRole('menuitemcheckbox', { name: 'Pastas compactas' }).click();
    assert.equal(await item('docs').count(), 1);
    await page.getByRole('button', { name: 'Opções do explorador' }).click();
    await page.getByRole('menuitemcheckbox', { name: 'Pastas compactas' }).click();
    assert.equal(await item('docs/guides').count(), 1);
    const resize = page.getByRole('separator', { name: 'Largura do explorador' });
    await resize.press('ArrowRight');
    assert.equal(await resize.getAttribute('aria-valuenow'), '270');
    evidence.checks.push('compact-folders-toggle-and-sidebar-resize');
    await item('src').click();
    await item('src/utils').click();
    assert.deepEqual(await tree.locator('[data-path^="src/utils/file"] .filename').allTextContents(), ['file2.ts', 'file10.ts']);
    await item('src/utils').press('ArrowLeft');
    assert.equal(await item('src/utils/file2.ts').count(), 0);
    await item('src/utils').press('ArrowRight');
    await item('src/utils').press('ArrowRight');
    assert.equal(await item('src/utils/file2.ts').evaluate(row => row === document.activeElement), true);
    await item('src/utils/file2.ts').press('Enter');
    await page.getByRole('tab', { name: /file2\.ts/ }).waitFor();
    evidence.checks.push('hierarchical-folders-natural-order-and-arrow-navigation');
    await page.getByRole('button', { name: 'Recolher pastas', exact: true }).click();
    assert.equal(await item('src/utils').count(), 0);
    // Switching to an existing editor reveals all its ancestors.
    await page.getByRole('tab', { name: /README\.md/ }).click();
    await page.getByRole('tab', { name: /file2\.ts/ }).click();
    await item('src/utils/file2.ts').waitFor();
    await item('src/utils').click(); // collapse and select the destination
    await page.getByRole('button', { name: 'Novo arquivo', exact: true }).click();
    await page.getByRole('textbox', { name: 'Nome do novo arquivo' }).fill('new.ts');
    await page.getByRole('textbox', { name: 'Nome do novo arquivo' }).press('Enter');
    await page.getByRole('tab', { name: /new\.ts/ }).waitFor();
    assert.equal(await readFile(path.join(repo, 'src/utils/new.ts'), 'utf8'), '');
    await item('src/utils/new.ts').press('F2');
    await page.getByRole('textbox', { name: 'Renomear arquivo' }).fill('renamed.ts');
    await page.getByRole('textbox', { name: 'Renomear arquivo' }).press('Enter');
    await item('src/utils/renamed.ts').waitFor();
    assert.equal(await readFile(path.join(repo, 'src/utils/renamed.ts'), 'utf8'), '');
    evidence.checks.push('inline-create-and-rename-use-real-core');
    await item('src/utils').click({ button: 'right' });
    await page.getByRole('menuitem', { name: 'Nova pasta', exact: true }).click();
    await page.getByRole('textbox', { name: 'Nome da nova pasta' }).fill('nested');
    await page.getByRole('textbox', { name: 'Nome da nova pasta' }).press('Enter');
    await item('src/utils/nested').waitFor();
    // A failed create keeps the input; Escape cancels it without replacing bytes.
    await item('src/utils').click({ button: 'right' });
    await page.getByRole('menuitem', { name: 'Novo arquivo', exact: true }).click();
    const input = page.getByRole('textbox', { name: 'Nome do novo arquivo' });
    await input.fill('file2.ts'); await input.press('Enter');
    await page.locator('.explorer-input-error').waitFor();
    assert.equal(await readFile(path.join(repo, 'src/utils/file2.ts'), 'utf8'), 'export const two = 2;\n');
    await input.press('Escape');
    await item('src/utils/renamed.ts').click({ button: 'right' });
    await page.getByRole('menuitem', { name: 'Copiar caminho relativo', exact: true }).click();
    await waitUntil(async () => await app.evaluate(({ clipboard }) => clipboard.readText()) === 'src/utils/renamed.ts');
    assert.equal(await app.evaluate(({ clipboard }) => clipboard.readText()), 'src/utils/renamed.ts');
    assert.equal((await page.evaluate(() => window.lab.call('copyRelativePath', { path: '../outside' }))).ok, false);
    assert.equal((await page.evaluate(() => window.lab.call('copyRelativePath', { path: '.git/config' }))).ok, false);
    assert.equal(await app.evaluate(({ clipboard }) => clipboard.readText()), 'src/utils/renamed.ts', 'Rejected paths must not replace the clipboard');
    evidence.checks.push('context-create-folder-and-collision-cancel');
    await item('AGENTS.md').click();
    assert.equal(await item('AGENTS.md').getByRole('img', { name: 'layer/ai', exact: true }).count(), 1);
    await page.screenshot({ path: path.join(reports, 'after-dark.png') });
    await page.getByRole('button', { name: 'Alternar tema' }).click();
    await page.screenshot({ path: path.join(reports, 'after-light.png') });
    await page.getByRole('button', { name: 'Alternar tema' }).click();
    assert.equal(await page.locator('.tabs').evaluate(strip => strip.scrollHeight <= strip.clientHeight), true, 'Tabs must not introduce a vertical scrollbar');
    await page.getByRole('tab', { name: /README\.md/ }).focus();
    await page.getByRole('tab', { name: /README\.md/ }).press('ArrowRight');
    assert.equal(await page.getByRole('tab', { name: /file2\.ts/ }).getAttribute('aria-selected'), 'true');
    await page.getByRole('tab', { name: /AGENTS\.md/ }).click();
    await page.getByRole('button', { name: 'Fechar src/utils/file2.ts', exact: true }).click();
    assert.equal(await page.getByRole('tab', { name: /AGENTS\.md/ }).getAttribute('aria-selected'), 'true', 'Closing an inactive tab preserves the active editor');
    await page.getByRole('tab', { name: /README\.md/ }).click();
    await page.locator('.monaco-editor .view-lines').first().click();
    await page.keyboard.press('ControlOrMeta+End'); await page.keyboard.type('Buffer preservado.');
    await page.waitForFunction(() => document.querySelector('.tab.dirty') !== null);
    await page.getByRole('button', { name: 'Fechar src/utils/renamed.ts', exact: true }).click();
    assert.equal(await page.locator('.modal').count(), 0, 'Closing a clean tab does not require saving another editor');
    assert.equal(await readFile(path.join(repo, 'README.md'), 'utf8'), '# Explorer\n');
    assert.equal(await page.locator('.tab.dirty').count(), 1);
    await page.getByRole('button', { name: /Salvar/ }).click();
    await waitUntil(async () => await page.locator('.tab.dirty').count() === 0);
    assert.match(await readFile(path.join(repo, 'README.md'), 'utf8'), /Buffer preservado/);
    evidence.checks.push('tabs-keyboard-inactive-close-and-independent-dirty-buffer');
    while (await page.locator('.tab > button[aria-label^="Fechar "]').count()) await page.locator('.tab > button[aria-label^="Fechar "]').first().click();
    await waitUntil(async () => await page.locator('.tab').count() === 0);
    assert.equal(await page.getByRole('tab').count(), 0);
    assert.equal(await page.locator('.monaco-host').count(), 0);
    await readme.click(); await page.getByRole('tab', { name: /README\.md/ }).waitFor();
    assert.equal(await page.locator('.tab').count(), 1);
    await page.getByRole('button', { name: 'Fechar README.md', exact: true }).click();
    await waitUntil(async () => await page.locator('.tab').count() === 0);
    evidence.checks.push('close-all-reopen-close-has-no-ghost-tab');
    await page.screenshot({ path: path.join(reports, 'all-tabs-closed.png') });
    assert.deepEqual(evidence.errors, []);
    evidence.status = 'passed';
  } catch (error) {
    evidence.status = 'failed'; evidence.failure = String(error);
    if (page) await page.screenshot({ path: path.join(reports, baseline ? 'before-failed.png' : 'failed.png') }).catch(() => {});
    throw error;
  } finally {
    if (app) await app.close().catch(() => {});
    await writeFile(path.join(reports, baseline ? 'baseline.json' : 'result.json'), JSON.stringify(evidence, null, 2));
    await rm(temp, { recursive: true, force: true });
  }
});
